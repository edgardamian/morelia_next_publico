/**
 * Obtiene el nombre estandarizado y el conteo oficial de ciudades por estrato poblacional IMCO.
 * Total nacional en el ICU: 72 ciudades divididas en 4 estratos:
 *  - Más de 1 millón: 21 ciudades
 *  - 500 mil a 1 millón: 17 ciudades
 *  - 250 a 500 mil: 23 ciudades
 *  - Menos de 250 mil: 11 ciudades
 */
window.getEstratoMeta = function(tamanoRaw, grupoRaw) {
  const norm = (str) => (str || '').toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '');

  const t = norm(tamanoRaw) + ' ' + norm(grupoRaw);

  if (t.includes('menos') || t.includes('< 250') || t.includes('menor')) {
    return {
      nombre: 'Menos de 250 mil habitantes',
      total: 11
    };
  }
  if (t.includes('250 a 500') || t.includes('250 mil a 500') || t.includes('250-500')) {
    return {
      nombre: 'De 250 a 500 mil habitantes',
      total: 23
    };
  }
  if (t.includes('500') || t.includes('quinientos')) {
    return {
      nombre: 'De 500 mil a 1 millón de habitantes',
      total: 17
    };
  }
  if (t.includes('mas') || t.includes('> 1') || t.includes('millon')) {
    return {
      nombre: 'Más de un millón de habitantes',
      total: 21
    };
  }
  return {
    nombre: tamanoRaw || 'Estrato poblacional',
    total: 21
  };
};
